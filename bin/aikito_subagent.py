"""Synchronize canonical Aikito Subagent definitions into supported agent configs."""

import argparse
import json
import os
import re
import shutil
import sys
import tomllib
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


DEFAULT_AGENTS_CONFIG = Path("agents.toml")
DEFAULT_SUBAGENTS_CONFIG = Path("subagents.toml")
SUBAGENTS_DIR = Path("subagents")
BACKUP_DIR = Path(".local/state/aikito/backups")

MARKER_PREFIX = "generated by aikito from subagents/"
SUBAGENT_NAME_PATTERN = re.compile(r"^[a-z][a-z0-9-]*$")

# Platform specific allowed fields
KNOWN_PLATFORM_FIELDS = {
    "codex": {"model", "model_reasoning_effort"},
    "claude-code": {"model", "effort"},
    "agy": set(),
    "github-copilot": {
        "name",
        "description",
        "model",
        "tools",
        "target",
        "disable-model-invocation",
        "user-invocable",
    },
}

FORMAT_EXTENSIONS = {
    "codex_toml": ".toml",
    "claude_markdown": ".md",
    "agy_markdown": ".md",
    "copilot_markdown": ".agent.md",
}


class SubagentConfigError(RuntimeError):
    """Raised when subagent configuration or target file operations fail."""


@dataclass(frozen=True)
class AgentSubagentConfig:
    agent_name: str
    display_name: str
    config_path: Path
    config_format: str


@dataclass(frozen=True)
class SubagentDefinition:
    name: str
    description: str
    agents: list[str]
    platform_configs: dict[str, dict[str, Any]]
    instructions: str


@dataclass
class PlanItem:
    agent_name: str
    subagent_name: str
    target_path: Path
    action: str  # OK, CREATE, UPDATE, CONFLICT, ORPHAN, SKIP, ERROR
    reason: str
    rendered_content: str = ""


def get_marker_text(subagent_name: str) -> str:
    return f"generated by aikito from subagents/{subagent_name}.md - edits will be overwritten"


def has_aikito_marker(file_path: Path) -> bool:
    if not file_path.is_file():
        return False
    try:
        with file_path.open("r", encoding="utf-8", errors="replace") as f:
            for _ in range(10):
                line = f.readline()
                if not line:
                    break
                if MARKER_PREFIX in line:
                    return True
    except Exception:
        return False
    return False


def load_all_agents(
    aikito_dir: Path, home: Path
) -> tuple[dict[str, AgentSubagentConfig], set[str]]:
    agents_toml_path = aikito_dir / DEFAULT_AGENTS_CONFIG
    if not agents_toml_path.is_file():
        raise SubagentConfigError(f"agents.toml not found at {agents_toml_path}")

    with agents_toml_path.open("rb") as f:
        data = tomllib.load(f)

    agents_data = data.get("agents", {})
    subagent_configs: dict[str, AgentSubagentConfig] = {}
    all_agent_names: set[str] = set()

    for agent_name, agent_info in agents_data.items():
        all_agent_names.add(agent_name)
        subagents_sec = agent_info.get("subagents")
        if not subagents_sec:
            continue

        raw_config_path = subagents_sec.get("config_path")
        config_format = subagents_sec.get("config_format")

        if not raw_config_path or not config_format:
            raise SubagentConfigError(
                f"Agent '{agent_name}' subagents section missing 'config_path' or 'config_format'"
            )

        if config_format not in FORMAT_EXTENSIONS:
            raise SubagentConfigError(
                f"Agent '{agent_name}' unsupported config_format '{config_format}'"
            )

        config_path = (home / raw_config_path).resolve()
        display_name = agent_info.get("display_name", agent_name)

        subagent_configs[agent_name] = AgentSubagentConfig(
            agent_name=agent_name,
            display_name=display_name,
            config_path=config_path,
            config_format=config_format,
        )

    return subagent_configs, all_agent_names


def load_subagent_definitions(
    aikito_dir: Path, allow_empty: bool = False
) -> dict[str, SubagentDefinition]:
    subagents_toml_path = aikito_dir / DEFAULT_SUBAGENTS_CONFIG
    if not subagents_toml_path.is_file():
        raise SubagentConfigError(f"subagents.toml not found at {subagents_toml_path}")

    with subagents_toml_path.open("rb") as f:
        data = tomllib.load(f)

    subagents_table = data.get("subagents")
    if subagents_table is None or not isinstance(subagents_table, dict):
        raise SubagentConfigError(
            "'subagents' table in subagents.toml is missing or empty"
        )
    if not subagents_table:
        if allow_empty:
            return {}
        raise SubagentConfigError(
            "'subagents' table in subagents.toml is missing or empty"
        )

    definitions: dict[str, SubagentDefinition] = {}

    for name, subagent_info in subagents_table.items():
        if not SUBAGENT_NAME_PATTERN.match(name) or ":" in name:
            raise SubagentConfigError(
                f"Invalid subagent name '{name}'. Must match ^[a-z][a-z0-9-]*$ and contain no colons."
            )

        description = subagent_info.get("description")
        if not description or not isinstance(description, str):
            raise SubagentConfigError(
                f"Subagent '{name}' missing valid 'description' string"
            )

        target_agents = subagent_info.get("agents")
        if not isinstance(target_agents, list) or not target_agents:
            raise SubagentConfigError(
                f"Subagent '{name}' 'agents' must be a non-empty list"
            )

        for ag in target_agents:
            if not isinstance(ag, str):
                raise SubagentConfigError(
                    f"Subagent '{name}' 'agents' list must contain strings"
                )

        # Load instructions file
        instr_path = aikito_dir / SUBAGENTS_DIR / f"{name}.md"
        if not instr_path.is_file():
            raise SubagentConfigError(
                f"Instructions file for subagent '{name}' not found at {instr_path}"
            )

        instructions = instr_path.read_text(encoding="utf-8").strip()
        if not instructions:
            raise SubagentConfigError(
                f"Instructions file for subagent '{name}' is empty"
            )

        # Load platform specific configs
        platform_configs: dict[str, dict[str, Any]] = {}
        for key, val in subagent_info.items():
            if key in ("description", "agents"):
                continue
            if isinstance(val, dict):
                validate_platform_opts(key, name, val)
                platform_configs[key] = val

        definitions[name] = SubagentDefinition(
            name=name,
            description=description,
            agents=target_agents,
            platform_configs=platform_configs,
            instructions=instructions,
        )

    return definitions


def validate_platform_opts(
    agent_name: str, subagent_name: str, platform_opts: dict[str, Any]
) -> dict[str, Any]:
    allowed = KNOWN_PLATFORM_FIELDS.get(agent_name, set())
    validated: dict[str, Any] = {}

    for k, v in platform_opts.items():
        if k not in allowed:
            raise SubagentConfigError(
                f"Subagent '{subagent_name}' contains unknown field '{k}' for platform '{agent_name}'. Allowed: {sorted(allowed)}"
            )
        if agent_name == "github-copilot":
            if k == "tools":
                if isinstance(v, str):
                    v = [v]
                if not isinstance(v, list) or not all(
                    isinstance(x, str) and x.strip() for x in v
                ):
                    raise SubagentConfigError(
                        f"Subagent '{subagent_name}' field 'tools' for platform '{agent_name}' must be a string or non-empty list of strings"
                    )
            elif k in ("disable-model-invocation", "user-invocable"):
                if not isinstance(v, bool):
                    raise SubagentConfigError(
                        f"Subagent '{subagent_name}' field '{k}' for platform '{agent_name}' must be a boolean"
                    )
            else:
                if not isinstance(v, str) or not v.strip():
                    raise SubagentConfigError(
                        f"Subagent '{subagent_name}' field '{k}' for platform '{agent_name}' must be a non-empty string"
                    )
        else:
            if not isinstance(v, str) or not v.strip():
                raise SubagentConfigError(
                    f"Subagent '{subagent_name}' field '{k}' for platform '{agent_name}' must be a non-empty string"
                )
        validated[k] = v

    return validated


def render_copilot_markdown(
    name: str, description: str, platform_opts: dict[str, Any], instructions: str
) -> str:
    marker = get_marker_text(name)
    lines = ["---"]

    opts = dict(platform_opts)
    if "name" not in opts:
        opts["name"] = name
    opts["description"] = description

    for k in sorted(opts.keys()):
        val = opts[k]
        if isinstance(val, bool):
            lines.append(f"{k}: {'true' if val else 'false'}")
        elif isinstance(val, list):
            encoded_list = json.dumps(val, ensure_ascii=False)
            lines.append(f"{k}: {encoded_list}")
        else:
            lines.append(f"{k}: {json.dumps(val, ensure_ascii=False)}")

    lines.append("---")
    lines.append(f"<!-- {marker} -->")
    lines.append("")
    lines.append(instructions)
    lines.append("")
    return "\n".join(lines)


def render_claude_markdown(
    name: str, description: str, platform_opts: dict[str, str], instructions: str
) -> str:
    marker = get_marker_text(name)
    lines = [
        "---",
        f"name: {json.dumps(name, ensure_ascii=False)}",
        f"description: {json.dumps(description, ensure_ascii=False)}",
    ]
    for k in sorted(platform_opts.keys()):
        lines.append(f"{k}: {json.dumps(platform_opts[k], ensure_ascii=False)}")
    lines.append("---")
    lines.append(f"<!-- {marker} -->")
    lines.append("")
    lines.append(instructions)
    lines.append("")
    return "\n".join(lines)


def render_codex_toml(
    name: str, description: str, platform_opts: dict[str, str], instructions: str
) -> str:
    if "'''" in instructions:
        raise SubagentConfigError(
            f"Instructions for subagent '{name}' contain triple single-quotes ('''), which is invalid for codex_toml literal string."
        )

    marker = get_marker_text(name)
    lines = [
        f"# {marker}",
        f"name = {json.dumps(name, ensure_ascii=False)}",
        f"description = {json.dumps(description, ensure_ascii=False)}",
    ]
    for k in sorted(platform_opts.keys()):
        lines.append(f"{k} = {json.dumps(platform_opts[k], ensure_ascii=False)}")

    lines.append("developer_instructions = '''")
    lines.append(instructions)
    lines.append("'''")
    lines.append("")
    rendered = "\n".join(lines)

    # Verify round-trip parsing for TOML
    try:
        tomllib.loads(rendered)
    except Exception as exc:
        raise SubagentConfigError(
            f"Rendered Codex TOML for '{name}' is invalid TOML: {exc}"
        )

    return rendered


def render_agy_markdown(
    name: str, description: str, platform_opts: dict[str, str], instructions: str
) -> str:
    marker = get_marker_text(name)
    lines = [
        "---",
        f"name: {json.dumps(name, ensure_ascii=False)}",
        f"description: {json.dumps(description, ensure_ascii=False)}",
    ]
    for k in sorted(platform_opts.keys()):
        lines.append(f"{k}: {json.dumps(platform_opts[k], ensure_ascii=False)}")
    lines.append("---")
    lines.append(f"<!-- {marker} -->")
    lines.append("")
    lines.append(instructions)
    lines.append("")
    return "\n".join(lines)


def render_subagent(
    definition: SubagentDefinition, agent_config: AgentSubagentConfig
) -> str:
    platform_raw = definition.platform_configs.get(agent_config.agent_name, {})
    platform_opts = validate_platform_opts(
        agent_config.agent_name, definition.name, platform_raw
    )

    if agent_config.config_format == "claude_markdown":
        return render_claude_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "agy_markdown":
        return render_agy_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "codex_toml":
        return render_codex_toml(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "copilot_markdown":
        return render_copilot_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    else:
        raise SubagentConfigError(f"Unsupported format '{agent_config.config_format}'")


def check_codex_enabled(home: Path) -> tuple[bool, str]:
    codex_config = home / ".codex" / "config.toml"
    if not codex_config.is_file():
        return True, ""
    try:
        with codex_config.open("rb") as f:
            data = tomllib.load(f)
        agents_sec = data.get("agents")
        if isinstance(agents_sec, dict) and agents_sec.get("enabled") is False:
            return (
                False,
                "Codex agents capability is explicitly disabled in ~/.codex/config.toml ([agents] enabled = false)",
            )
    except Exception:
        pass
    return True, ""


def get_target_subagent_path(
    agent_config: AgentSubagentConfig, subagent_name: str
) -> Path:
    if agent_config.config_format == "agy_markdown":
        return agent_config.config_path / subagent_name / "agent.md"
    ext = FORMAT_EXTENSIONS[agent_config.config_format]
    return agent_config.config_path / f"{subagent_name}{ext}"


def build_plan(
    aikito_dir: Path, home: Path, allow_empty: bool = False
) -> tuple[list[PlanItem], dict[str, AgentSubagentConfig]]:
    subagent_configs, all_agent_names = load_all_agents(aikito_dir, home)
    subagent_defs = load_subagent_definitions(aikito_dir, allow_empty=allow_empty)

    # Check that referenced agents exist in agents.toml with subagents config
    for sub_name, definition in subagent_defs.items():
        for ag_name in definition.agents:
            if ag_name not in subagent_configs:
                raise SubagentConfigError(
                    f"Subagent '{sub_name}' targets agent '{ag_name}', but '{ag_name}' has no [agents.{ag_name}.subagents] configuration in agents.toml"
                )

    plan: list[PlanItem] = []

    # Handle agents without subagents config (SKIP)
    for ag_name in sorted(all_agent_names):
        if ag_name not in subagent_configs:
            plan.append(
                PlanItem(
                    agent_name=ag_name,
                    subagent_name="*",
                    target_path=Path(""),
                    action="SKIP",
                    reason="Agent has no subagents section in agents.toml",
                )
            )

    for agent_name, agent_config in subagent_configs.items():
        if agent_name == "codex":
            enabled, msg = check_codex_enabled(home)
            if not enabled:
                plan.append(
                    PlanItem(
                        agent_name=agent_name,
                        subagent_name="*",
                        target_path=agent_config.config_path,
                        action="ERROR",
                        reason=msg,
                    )
                )

        target_ext = FORMAT_EXTENSIONS[agent_config.config_format]

        # Subagents targeting this agent
        defined_subagents_for_agent: set[str] = set()

        for sub_name in sorted(subagent_defs.keys()):
            definition = subagent_defs[sub_name]
            if agent_name not in definition.agents:
                continue

            defined_subagents_for_agent.add(sub_name)
            target_path = get_target_subagent_path(agent_config, sub_name)

            try:
                rendered = render_subagent(definition, agent_config)
            except SubagentConfigError as exc:
                plan.append(
                    PlanItem(
                        agent_name=agent_name,
                        subagent_name=sub_name,
                        target_path=target_path,
                        action="ERROR",
                        reason=str(exc),
                    )
                )
                continue

            if not target_path.exists():
                plan.append(
                    PlanItem(
                        agent_name=agent_name,
                        subagent_name=sub_name,
                        target_path=target_path,
                        action="CREATE",
                        reason="Target file does not exist",
                        rendered_content=rendered,
                    )
                )
            else:
                if has_aikito_marker(target_path):
                    current_content = target_path.read_text(
                        encoding="utf-8", errors="replace"
                    )
                    if current_content == rendered:
                        plan.append(
                            PlanItem(
                                agent_name=agent_name,
                                subagent_name=sub_name,
                                target_path=target_path,
                                action="OK",
                                reason="Up to date",
                                rendered_content=rendered,
                            )
                        )
                    else:
                        plan.append(
                            PlanItem(
                                agent_name=agent_name,
                                subagent_name=sub_name,
                                target_path=target_path,
                                action="UPDATE",
                                reason="Content changed",
                                rendered_content=rendered,
                            )
                        )
                else:
                    plan.append(
                        PlanItem(
                            agent_name=agent_name,
                            subagent_name=sub_name,
                            target_path=target_path,
                            action="CONFLICT",
                            reason="Target file exists without Aikito marker",
                            rendered_content=rendered,
                        )
                    )

        # Detect orphans in agent's config_path directory
        if agent_config.config_path.is_dir():
            if agent_config.config_format == "agy_markdown":
                for sub_dir in sorted(agent_config.config_path.iterdir()):
                    if sub_dir.is_dir():
                        agent_md = sub_dir / "agent.md"
                        sub_name = sub_dir.name
                        if (
                            sub_name not in defined_subagents_for_agent
                            and has_aikito_marker(agent_md)
                        ):
                            plan.append(
                                PlanItem(
                                    agent_name=agent_name,
                                    subagent_name=sub_name,
                                    target_path=agent_md,
                                    action="ORPHAN",
                                    reason="Managed subagent file is no longer defined in subagents.toml",
                                )
                            )
            else:
                for item in sorted(agent_config.config_path.iterdir()):
                    if item.is_file() and item.suffix == target_ext:
                        sub_name = item.stem
                        if (
                            sub_name not in defined_subagents_for_agent
                            and has_aikito_marker(item)
                        ):
                            plan.append(
                                PlanItem(
                                    agent_name=agent_name,
                                    subagent_name=sub_name,
                                    target_path=item,
                                    action="ORPHAN",
                                    reason="Managed subagent file is no longer defined in subagents.toml",
                                )
                            )

    return plan, subagent_configs


def _backup_file(home: Path, agent_name: str, target_path: Path) -> Path | None:
    if not target_path.is_file():
        return None
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    backup_path = home / BACKUP_DIR / agent_name / f"{timestamp}-{target_path.name}"
    backup_path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(target_path, backup_path)
    return backup_path


def _write_file_atomic(target_path: Path, content: str) -> None:
    target_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = target_path.with_suffix(f"{target_path.suffix}.tmp.{os.getpid()}")
    tmp_path.write_text(content, encoding="utf-8")
    tmp_path.replace(target_path)


def sync_subagent_configs(
    aikito_dir: Path,
    home: Path,
    dry_run: bool = False,
    force_targets: list[str] | None = None,
    prune: bool = False,
) -> bool:
    normalized_force: set[str] = set()
    if force_targets is not None:
        if not force_targets:
            raise SubagentConfigError(
                "--force requires explicit <agent>/<subagent> target(s), e.g. --force claude-code/formatter"
            )
        for ft in force_targets:
            if "/" not in ft or len(ft.split("/")) != 2:
                raise SubagentConfigError(
                    f"Invalid --force target '{ft}'. Must be in format <agent>/<subagent>"
                )
            normalized_force.add(ft)

    plan, _ = build_plan(aikito_dir, home, allow_empty=True)

    has_errors = any(item.action == "ERROR" for item in plan)
    has_unforced_conflicts = any(
        item.action == "CONFLICT"
        and f"{item.agent_name}/{item.subagent_name}" not in normalized_force
        for item in plan
    )

    print(f"[INFO] Subagent synchronization plan (dry_run={dry_run}):")

    for item in plan:
        target_key = f"{item.agent_name}/{item.subagent_name}"
        if item.action == "SKIP":
            print(f"  [SKIP] {item.agent_name} ({item.reason})")
        elif item.action == "OK":
            print(f"  [OK] {target_key}")
        elif item.action == "CREATE":
            print(f"  [CREATE] {target_key} -> {item.target_path}")
        elif item.action == "UPDATE":
            print(f"  [UPDATE] {target_key} -> {item.target_path}")
        elif item.action == "CONFLICT":
            if target_key in normalized_force:
                print(f"  [FORCE UPDATE] {target_key} -> {item.target_path}")
            else:
                print(
                    f"  [CONFLICT] {target_key} -> {item.target_path} ({item.reason}. Use --force {target_key} to overwrite)"
                )
        elif item.action == "ORPHAN":
            if prune:
                print(f"  [PRUNE] {target_key} -> {item.target_path}")
            else:
                print(
                    f"  [ORPHAN] {target_key} -> {item.target_path} ({item.reason}. Use --prune to remove)"
                )
        elif item.action == "ERROR":
            print(f"  [ERROR] {target_key}: {item.reason}")

    if has_errors:
        print(
            "[ERROR] Synchronization aborted due to errors in plan. No changes were made.",
            file=sys.stderr,
        )
        return False

    if has_unforced_conflicts:
        print(
            "[WARN] Synchronization aborted due to unhandled conflicts. No changes were made.",
            file=sys.stderr,
        )
        return False

    if dry_run:
        print("[SUCCESS] Subagent synchronization plan completed (dry-run).")
        return True

    # Perform physical file modifications only when there are no errors or unhandled conflicts
    for item in plan:
        target_key = f"{item.agent_name}/{item.subagent_name}"
        if item.action == "CREATE":
            _write_file_atomic(item.target_path, item.rendered_content)
        elif item.action == "UPDATE":
            _backup_file(home, item.agent_name, item.target_path)
            _write_file_atomic(item.target_path, item.rendered_content)
        elif item.action == "CONFLICT" and target_key in normalized_force:
            _backup_file(home, item.agent_name, item.target_path)
            _write_file_atomic(item.target_path, item.rendered_content)
        elif item.action == "ORPHAN" and prune:
            _backup_file(home, item.agent_name, item.target_path)
            item.target_path.unlink()

    print("[SUCCESS] Subagent synchronization completed successfully.")
    return True


def status_subagent_configs(aikito_dir: Path, home: Path) -> bool:
    plan, _ = build_plan(aikito_dir, home)
    all_ok = True

    print("[INFO] Subagent Status Report:")
    for item in plan:
        target_key = f"{item.agent_name}/{item.subagent_name}"
        if item.action == "SKIP":
            print(f"  [SKIP] {item.agent_name}: no subagents configured")
        elif item.action == "OK":
            print(f"  [OK] {target_key}")
        elif item.action in ("CREATE", "UPDATE"):
            all_ok = False
            print(
                f"  [{item.action}] {target_key} -> {item.target_path} ({item.reason})"
            )
        elif item.action == "CONFLICT":
            all_ok = False
            print(f"  [CONFLICT] {target_key} -> {item.target_path}")
        elif item.action == "ORPHAN":
            all_ok = False
            print(f"  [ORPHAN] {target_key} -> {item.target_path}")
        elif item.action == "ERROR":
            all_ok = False
            print(f"  [ERROR] {target_key}: {item.reason}")

    if all_ok:
        print("[SUCCESS] All subagent configurations are up-to-date.")
    return all_ok
