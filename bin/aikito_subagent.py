def _split_cordis_patch_items(text: str) -> list[tuple[int, int, str]]:
    """Split YAML list into (start_idx, end_idx, item_text) tuples for top-level list items."""
    item_starts: list[int] = []
    for match in re.finditer(r"(?m)^-[ \t]+", text):
        item_starts.append(match.start())

    if not item_starts:
        stripped = text.lstrip()
        if stripped.startswith("-"):
            item_starts.append(text.find("-"))
        else:
            return []

    items: list[tuple[int, int, str]] = []
    for i, start in enumerate(item_starts):
        end = item_starts[i + 1] if i + 1 < len(item_starts) else len(text)
        items.append((start, end, text[start:end]))
    return items


def _parse_cordis_subagent_plugin_item(item_text: str) -> dict[str, Any]:
    """Parse key fields from a single Cordis plugin item in YAML."""
    result: dict[str, Any] = {}
    lines = item_text.splitlines()
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if ":" in stripped:
            k, v = stripped.split(":", 1)
            k = k.strip().lstrip("- ").strip()
            v = v.strip().strip("'\"")
            if k in ("id", "name", "toolName", "provider"):
                result[k] = v
    return result


def get_dsh_cordis_subagent_item(text: str, name: str) -> str | None:
    """Find the raw YAML item block for aikito-subagent-<name> if present."""
    if not text.strip():
        return None
    items = _split_cordis_patch_items(text)
    for _, _, item_text in items:
        info = _parse_cordis_subagent_plugin_item(item_text)
        plugin_id = info.get("id", "")
        plugin_name = info.get("name", "")
        tool_name = info.get("toolName", "")
        if plugin_id == f"aikito-subagent-{name}" or (
            plugin_name == "@deepseek-ai/dsh-tool-subagent" and tool_name == name
        ):
            return item_text
    return None


def get_all_dsh_cordis_subagents(text: str) -> list[str]:
    """Find all subagent names managed by Aikito in cordis.patch.yml."""
    if not text.strip():
        return []
    names = []
    items = _split_cordis_patch_items(text)
    for _, _, item_text in items:
        if not has_aikito_marker_text(item_text):
            continue
        info = _parse_cordis_subagent_plugin_item(item_text)
        plugin_id = info.get("id", "")
        if plugin_id.startswith("aikito-subagent-"):
            names.append(plugin_id.removeprefix("aikito-subagent-"))
        elif (
            info.get("name") == "@deepseek-ai/dsh-tool-subagent" and "toolName" in info
        ):
            names.append(info["toolName"])
    return names


def update_dsh_cordis_subagent(text: str, name: str, rendered_block: str) -> str:
    """Update or append an @deepseek-ai/dsh-tool-subagent plugin item in cordis.patch.yml."""
    if not text.strip():
        return rendered_block + "\n"

    items = _split_cordis_patch_items(text)
    for start, end, item_text in items:
        info = _parse_cordis_subagent_plugin_item(item_text)
        plugin_id = info.get("id", "")
        plugin_name = info.get("name", "")
        tool_name = info.get("toolName", "")
        if plugin_id == f"aikito-subagent-{name}" or (
            plugin_name == "@deepseek-ai/dsh-tool-subagent" and tool_name == name
        ):
            trailing = "" if item_text.endswith("\n") else "\n"
            return text[:start] + rendered_block + trailing + text[end:]

    separator = (
        "\n" if text.endswith("\n\n") else ("\n\n" if text.endswith("\n") else "\n\n")
    )
    return text.rstrip() + separator + rendered_block + "\n"


def remove_dsh_cordis_subagent(text: str, name: str) -> str:
    """Remove an @deepseek-ai/dsh-tool-subagent plugin item from cordis.patch.yml."""
    if not text.strip():
        return ""

    items = _split_cordis_patch_items(text)
    for start, end, item_text in items:
        info = _parse_cordis_subagent_plugin_item(item_text)
        plugin_id = info.get("id", "")
        plugin_name = info.get("name", "")
        tool_name = info.get("toolName", "")
        if plugin_id == f"aikito-subagent-{name}" or (
            plugin_name == "@deepseek-ai/dsh-tool-subagent" and tool_name == name
        ):
            new_text = (text[:start] + text[end:]).strip()
            return (new_text + "\n") if new_text else ""
    return text


def render_dsh_cordis_subagent(
    name: str, description: str, platform_opts: dict[str, Any], instructions: str
) -> str:
    marker = get_marker_text(name)
    provider = str(platform_opts.get("provider", "spawn"))
    lines = [
        f"- id: aikito-subagent-{name}",
        f"  # {marker}",
        "  name: '@deepseek-ai/dsh-tool-subagent'",
        "  config:",
        f"    provider: {provider}",
        f"    toolName: {name}",
    ]
    if "model" in platform_opts or "maxTokens" in platform_opts:
        lines.append("    agentOptions:")
        if "model" in platform_opts:
            lines.append(
                f"      model: {json.dumps(platform_opts['model'], ensure_ascii=False)}"
            )
        if "maxTokens" in platform_opts:
            lines.append(f"      maxTokens: {platform_opts['maxTokens']}")
    if "backgroundMode" in platform_opts:
        lines.append(f"    backgroundMode: {platform_opts['backgroundMode']}")
    if "tools" in platform_opts and isinstance(platform_opts["tools"], list):
        lines.append("    toolFilter:")
        lines.append("      allow:")
        for t in platform_opts["tools"]:
            lines.append(f"        - {t}")

    indented_instructions = "\n".join(
        ("      " + line) if line else "" for line in instructions.splitlines()
    )
    lines.append("    persona: |-")
    lines.append(indented_instructions)
    return "\n".join(lines)


def render_subagent(
    definition: SubagentDefinition, agent_config: AgentSubagentConfig
) -> str:
    platform_raw = definition.platform_configs.get(agent_config.agent_name, {})
    platform_opts = validate_platform_opts(
        agent_config.agent_name, definition.name, platform_raw
    )

    if agent_config.config_format == "claude_markdown":
        return render_claude_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "agy_markdown":
        return render_agy_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "codex_toml":
        return render_codex_toml(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "copilot_markdown":
        return render_copilot_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "opencode_markdown":
        return render_opencode_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "dsh_cordis_subagent":
        return render_dsh_cordis_subagent(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "grok_markdown":
        return render_grok_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    elif agent_config.config_format == "pi_markdown":
        return render_pi_markdown(
            definition.name,
            definition.description,
            platform_opts,
            definition.instructions,
        )
    else:
        raise SubagentConfigError(f"Unsupported format '{agent_config.config_format}'")


def check_codex_enabled(home: Path) -> tuple[bool, str]:
    codex_config = home / ".codex" / "config.toml"
    if not codex_config.is_file():
        return True, ""
    try:
        with codex_config.open("rb") as f:
            data = tomllib.load(f)
        agents_sec = data.get("agents")
        if isinstance(agents_sec, dict) and agents_sec.get("enabled") is False:
            return (
                False,
                "Codex agents capability is explicitly disabled in ~/.codex/config.toml ([agents] enabled = false)",
            )
    except Exception:
        pass
    return True, ""


def get_target_subagent_path(
    agent_config: AgentSubagentConfig, subagent_name: str
) -> Path:
    if agent_config.config_format == "agy_markdown":
        return agent_config.config_path / subagent_name / "agent.md"
    if agent_config.config_format == "dsh_cordis_subagent":
        return agent_config.config_path
    ext = FORMAT_EXTENSIONS[agent_config.config_format]
    return agent_config.config_path / f"{subagent_name}{ext}"


def build_plan(
    aikito_dir: Path,
    home: Path,
    allow_empty: bool = False,
    gate_installed: bool = True,
) -> tuple[list[PlanItem], dict[str, AgentSubagentConfig]]:
    subagent_configs, all_agent_names = load_all_agents(aikito_dir, home)
    subagent_defs = load_subagent_definitions(aikito_dir, allow_empty=allow_empty)

    # Check that referenced agents exist in agents.toml with subagents config
    for sub_name, definition in subagent_defs.items():
        for ag_name in definition.agents:
            if ag_name not in subagent_configs:
                raise SubagentConfigError(
                    f"Subagent '{sub_name}' targets agent '{ag_name}', but '{ag_name}' has no [agents.{ag_name}.subagents] configuration in agents.toml"
                )

    plan: list[PlanItem] = []

    # Handle agents without subagents config (SKIP)
    for ag_name in sorted(all_agent_names):
        if ag_name not in subagent_configs:
            plan.append(
                PlanItem(
                    agent_name=ag_name,
                    subagent_name="*",
                    target_path=Path(""),
                    action="SKIP",
                    reason="Agent has no subagents section in agents.toml",
                )
            )

    for agent_name, agent_config in subagent_configs.items():
        if gate_installed and is_agent_installed(agent_name, home) is False:
            has_subagents = False
            for sub_name, definition in sorted(subagent_defs.items()):
                if agent_name in definition.agents:
                    has_subagents = True
                    target_path = get_target_subagent_path(agent_config, sub_name)
                    plan.append(
                        PlanItem(
                            agent_name=agent_name,
                            subagent_name=sub_name,
                            target_path=target_path,
                            action="SKIP",
                            reason=f"Agent '{agent_name}' is not installed on this host",
                        )
                    )
            if not has_subagents:
                plan.append(
                    PlanItem(
                        agent_name=agent_name,
                        subagent_name="*",
                        target_path=agent_config.config_path,
                        action="SKIP",
                        reason=f"Agent '{agent_name}' is not installed on this host",
                    )
                )
            continue
        if (
            agent_config.requires_path is not None
            and not agent_config.requires_path.exists()
        ):
            plan.append(
                PlanItem(
                    agent_name=agent_name,
                    subagent_name="*",
                    target_path=agent_config.config_path,
                    action="SKIP",
                    reason=f"Optional subagent capability is not installed at {agent_config.requires_path}",
                )
            )
            continue

        if agent_name == "codex":
            enabled, msg = check_codex_enabled(home)
            if not enabled:
                plan.append(
                    PlanItem(
                        agent_name=agent_name,
                        subagent_name="*",
                        target_path=agent_config.config_path,
                        action="ERROR",
                        reason=msg,
                    )
                )

        target_ext = FORMAT_EXTENSIONS[agent_config.config_format]

        # Subagents targeting this agent
        defined_subagents_for_agent: set[str] = set()

        if agent_config.config_format == "dsh_cordis_subagent":
            patch_file = agent_config.config_path
            patch_text = (
                patch_file.read_text(encoding="utf-8") if patch_file.is_file() else ""
            )
            for sub_name in sorted(subagent_defs.keys()):
                definition = subagent_defs[sub_name]
                if agent_name not in definition.agents:
                    continue
                defined_subagents_for_agent.add(sub_name)
                try:
                    rendered = render_subagent(definition, agent_config)
                except SubagentConfigError as exc:
                    plan.append(
                        PlanItem(
                            agent_name=agent_name,
                            subagent_name=sub_name,
                            target_path=patch_file,
                            action="ERROR",
                            reason=str(exc),
                        )
                    )
                    continue

                existing_block = get_dsh_cordis_subagent_item(patch_text, sub_name)
                if existing_block is None:
                    plan.append(
                        PlanItem(
                            agent_name=agent_name,
                            subagent_name=sub_name,
                            target_path=patch_file,
                            action="CREATE",
                            reason="Subagent plugin item does not exist in cordis.patch.yml",
                            rendered_content=rendered,
                        )
                    )
                elif has_aikito_marker_text(existing_block):
                    if existing_block.strip() == rendered.strip():
                        plan.append(
                            PlanItem(
                                agent_name=agent_name,
                                subagent_name=sub_name,
                                target_path=patch_file,
                                action="OK",
                                reason="Up to date",
                                rendered_content=rendered,
                            )
                        )
                    else:
                        plan.append(
                            PlanItem(
                                agent_name=agent_name,
                                subagent_name=sub_name,
                                target_path=patch_file,
                                action="UPDATE",
                                reason="Subagent configuration changed in cordis.patch.yml",
                                rendered_content=rendered,
                            )
                        )
                else:
                    plan.append(
                        PlanItem(
                            agent_name=agent_name,
                            subagent_name=sub_name,
                            target_path=patch_file,
                            action="CONFLICT",
                            reason="Target plugin item exists without Aikito marker",
                            rendered_content=rendered,
                        )
                    )

            # Detect orphans in cordis.patch.yml
            for managed_name in get_all_dsh_cordis_subagents(patch_text):
                if managed_name not in defined_subagents_for_agent:
                    plan.append(
                        PlanItem(
                            agent_name=agent_name,
                            subagent_name=managed_name,
                            target_path=patch_file,
                            action="ORPHAN",
                            reason="Managed subagent in cordis.patch.yml is no longer defined in subagents.toml",
                        )
                    )
            continue

        for sub_name in sorted(subagent_defs.keys()):
            definition = subagent_defs[sub_name]
            if agent_name not in definition.agents:
                continue

            defined_subagents_for_agent.add(sub_name)
            target_path = get_target_subagent_path(agent_config, sub_name)

            try:
                rendered = render_subagent(definition, agent_config)
            except SubagentConfigError as exc:
                plan.append(
                    PlanItem(
                        agent_name=agent_name,
                        subagent_name=sub_name,
                        target_path=target_path,
                        action="ERROR",
                        reason=str(exc),
                    )
                )
                continue

            if not target_path.exists():
                plan.append(
                    PlanItem(
                        agent_name=agent_name,
                        subagent_name=sub_name,
                        target_path=target_path,
                        action="CREATE",
                        reason="Target file does not exist",
                        rendered_content=rendered,
                    )
                )
            else:
                if has_aikito_marker(target_path):
                    current_content = target_path.read_text(
                        encoding="utf-8", errors="replace"
                    )
                    if current_content == rendered:
                        plan.append(
                            PlanItem(
                                agent_name=agent_name,
                                subagent_name=sub_name,
                                target_path=target_path,
                                action="OK",
                                reason="Up to date",
                                rendered_content=rendered,
                            )
                        )
                    else:
                        plan.append(
                            PlanItem(
                                agent_name=agent_name,
                                subagent_name=sub_name,
                                target_path=target_path,
                                action="UPDATE",
                                reason="Content changed",
                                rendered_content=rendered,
                            )
                        )
                else:
                    plan.append(
                        PlanItem(
                            agent_name=agent_name,
                            subagent_name=sub_name,
                            target_path=target_path,
                            action="CONFLICT",
                            reason="Target file exists without Aikito marker",
                            rendered_content=rendered,
                        )
                    )

        # Detect orphans in agent's config_path directory
        if agent_config.config_path.is_dir():
            if agent_config.config_format == "agy_markdown":
                for sub_dir in sorted(agent_config.config_path.iterdir()):
                    if sub_dir.is_dir():
                        agent_md = sub_dir / "agent.md"
                        sub_name = sub_dir.name
                        if (
                            sub_name not in defined_subagents_for_agent
                            and has_aikito_marker(agent_md)
                        ):
                            plan.append(
                                PlanItem(
                                    agent_name=agent_name,
                                    subagent_name=sub_name,
                                    target_path=agent_md,
                                    action="ORPHAN",
                                    reason="Managed subagent file is no longer defined in subagents.toml",
                                )
                            )
            else:
                for item in sorted(agent_config.config_path.iterdir()):
                    if item.is_file() and item.suffix == target_ext:
                        sub_name = item.stem
                        if (
                            sub_name not in defined_subagents_for_agent
                            and has_aikito_marker(item)
                        ):
                            plan.append(
                                PlanItem(
                                    agent_name=agent_name,
                                    subagent_name=sub_name,
                                    target_path=item,
                                    action="ORPHAN",
                                    reason="Managed subagent file is no longer defined in subagents.toml",
                                )
                            )

    return plan, subagent_configs


def _backup_file(home: Path, agent_name: str, target_path: Path) -> Path | None:
    if not target_path.is_file():
        return None
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    backup_path = home / BACKUP_DIR / agent_name / f"{timestamp}-{target_path.name}"
    backup_path.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(target_path, backup_path)
    return backup_path


def _write_file_atomic(target_path: Path, content: str) -> None:
    target_path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = target_path.with_suffix(f"{target_path.suffix}.tmp.{os.getpid()}")
    tmp_path.write_text(content, encoding="utf-8")
    tmp_path.replace(target_path)


def sync_subagent_configs(
    aikito_dir: Path,
    home: Path,
    dry_run: bool = False,
    force_targets: list[str] | None = None,
    prune: bool = False,
    all_agents: bool = False,
) -> bool:
    normalized_force: set[str] = set()
    if force_targets is not None:
        if not force_targets:
            raise SubagentConfigError(
                "--force requires explicit <agent>/<subagent> target(s), e.g. --force claude-code/verifier"
            )
        for ft in force_targets:
            if "/" not in ft or len(ft.split("/")) != 2:
                raise SubagentConfigError(
                    f"Invalid --force target '{ft}'. Must be in format <agent>/<subagent>"
                )
            normalized_force.add(ft)

    plan, _ = build_plan(aikito_dir, home, allow_empty=True, gate_installed=not all_agents)

    has_errors = any(item.action == "ERROR" for item in plan)
    has_unforced_conflicts = any(
        item.action == "CONFLICT"
        and f"{item.agent_name}/{item.subagent_name}" not in normalized_force
        for item in plan
    )

    print(f"[INFO] Subagent synchronization plan (dry_run={dry_run}):")

    for item in plan:
        target_key = f"{item.agent_name}/{item.subagent_name}"
        if item.action == "SKIP":
            print(f"  [SKIP] {item.agent_name} ({item.reason})")
        elif item.action == "OK":
            print(f"  [OK] {target_key}")
        elif item.action == "CREATE":
            print(f"  [CREATE] {target_key} -> {item.target_path}")
        elif item.action == "UPDATE":
            print(f"  [UPDATE] {target_key} -> {item.target_path}")
        elif item.action == "CONFLICT":
            if target_key in normalized_force:
                print(f"  [FORCE UPDATE] {target_key} -> {item.target_path}")
            else:
                print(
                    f"  [CONFLICT] {target_key} -> {item.target_path} ({item.reason}. Use --force {target_key} to overwrite)"
                )
        elif item.action == "ORPHAN":
            if prune:
                print(f"  [PRUNE] {target_key} -> {item.target_path}")
            else:
                print(
                    f"  [ORPHAN] {target_key} -> {item.target_path} ({item.reason}. Use --prune to remove)"
                )
        elif item.action == "ERROR":
            print(f"  [ERROR] {target_key}: {item.reason}")

    if has_errors:
        print(
            "[ERROR] Synchronization aborted due to errors in plan. No changes were made.",
            file=sys.stderr,
        )
        return False

    if has_unforced_conflicts:
        print(
            "[WARN] Synchronization aborted due to unhandled conflicts. No changes were made.",
            file=sys.stderr,
        )
        return False

    if dry_run:
        print("[SUCCESS] Subagent synchronization plan completed (dry-run).")
        return True

    # Perform physical file modifications only when there are no errors or unhandled conflicts
    for item in plan:
        target_key = f"{item.agent_name}/{item.subagent_name}"
        if item.agent_name == "dsh" or item.target_path.name == "cordis.patch.yml":
            if item.action in ("CREATE", "UPDATE") or (
                item.action == "CONFLICT" and target_key in normalized_force
            ):
                if item.action == "UPDATE" or (
                    item.action == "CONFLICT" and target_key in normalized_force
                ):
                    _backup_file(home, item.agent_name, item.target_path)
                curr_text = (
                    item.target_path.read_text(encoding="utf-8")
                    if item.target_path.is_file()
                    else ""
                )
                new_text = update_dsh_cordis_subagent(
                    curr_text, item.subagent_name, item.rendered_content
                )
                _write_file_atomic(item.target_path, new_text)
            elif item.action == "ORPHAN" and prune:
                _backup_file(home, item.agent_name, item.target_path)
                curr_text = (
                    item.target_path.read_text(encoding="utf-8")
                    if item.target_path.is_file()
                    else ""
                )
                new_text = remove_dsh_cordis_subagent(curr_text, item.subagent_name)
                _write_file_atomic(item.target_path, new_text)
        else:
            if item.action == "CREATE":
                _write_file_atomic(item.target_path, item.rendered_content)
            elif item.action == "UPDATE":
                _backup_file(home, item.agent_name, item.target_path)
                _write_file_atomic(item.target_path, item.rendered_content)
            elif item.action == "CONFLICT" and target_key in normalized_force:
                _backup_file(home, item.agent_name, item.target_path)
                _write_file_atomic(item.target_path, item.rendered_content)
            elif item.action == "ORPHAN" and prune:
                _backup_file(home, item.agent_name, item.target_path)
                item.target_path.unlink()

    print("[SUCCESS] Subagent synchronization completed successfully.")
    return True


def status_subagent_configs(aikito_dir: Path, home: Path) -> bool:
    plan, _ = build_plan(aikito_dir, home)
    all_ok = True

    print("[INFO] Subagent Status Report:")
    for item in plan:
        target_key = f"{item.agent_name}/{item.subagent_name}"
        if item.action == "SKIP":
            print(f"  [SKIP] {item.agent_name}: no subagents configured")
        elif item.action == "OK":
            print(f"  [OK] {target_key}")
        elif item.action in ("CREATE", "UPDATE"):
            all_ok = False
            print(
                f"  [{item.action}] {target_key} -> {item.target_path} ({item.reason})"
            )
        elif item.action == "CONFLICT":
            all_ok = False
            print(f"  [CONFLICT] {target_key} -> {item.target_path}")
        elif item.action == "ORPHAN":
            all_ok = False
            print(f"  [ORPHAN] {target_key} -> {item.target_path}")
        elif item.action == "ERROR":
            all_ok = False
            print(f"  [ERROR] {target_key}: {item.reason}")

    if all_ok:
        print("[SUCCESS] All subagent configurations are up-to-date.")
    return all_ok
