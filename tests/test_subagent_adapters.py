GOLDEN = json.loads(
    (Path(__file__).parent / "fixtures/subagent-adapter-parity.json").read_text()
)


@pytest.mark.parametrize("format", GOLDEN)
def test_rendering_preserves_existing_bytes(format):
    sample = GOLDEN[format]
    definition = SubagentDefinition(
        "review",
        "Review changes",
        ["example"],
        {"example": sample["options"]},
        "Review carefully.\n\nKeep 用户 context.",
    )
    config = AgentSubagentConfig("example", "Example", Path("/target"), format)
    assert render_subagent(definition, config) == sample["rendered"]


def test_custom_platform_reuses_adapter(tmp_path):
    ws, home = tmp_path / "ws", tmp_path / "home"
    ws.mkdir()
    home.mkdir()
    write_agents(
        ws,
        """[agents.example]
[agents.example.detect]
paths = [".example"]
[agents.example.subagents]
config_path = ".example/agents"
config_format = "claude_markdown"
""",
    )
    (home / ".example").mkdir()
    (ws / "subagents/review.md").write_text("""---
description: "Review changes"
agents: ["example"]
example: {"model": "example", "effort": "high"}
---
Review carefully.
""")
    plan = build_subagent_plan(ws, home)
    assert plan.operations[0].action == "CREATE"
    assert 'model: "example"' in plan.file_plans[0].final_content
    agents = load_agent_definitions(ws, home)
    with pytest.raises(SubagentConfigError, match="unknown field"):
        validate_platform_opts("example", "review", {"maxTokens": 1}, agents=agents)
    with pytest.raises(SubagentConfigError, match="no defined"):
        validate_platform_opts("undefined", "review", {}, agents=agents)


@pytest.mark.parametrize(
    "format,suffix",
    [
        ("agy_markdown", "review/agent.md"),
        ("copilot_markdown", "review.agent.md"),
        ("codex_toml", "review.toml"),
    ],
)
def test_paths_and_managed_orphans(tmp_path, format, suffix):
    config = AgentSubagentConfig("example", "Example", tmp_path, format)
    path = get_target_subagent_path(config, "review")
    assert path == tmp_path / suffix
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# generated by aikito from subagents/review.md\n")
    assert get_subagent_adapter(format).list_managed(tmp_path) == {"review": path}


