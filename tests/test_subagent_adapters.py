def test_shared_patch_freezes_content_and_protects_stale_plan(tmp_path):
    from aikito.subagent import execute_subagent_plan

    ws, home = tmp_path / "ws", tmp_path / "home"
    write_agents(
        ws,
        """[agents.example]
[agents.example.detect]
paths = [".example"]
[agents.example.subagents]
config_path = ".example/cordis.patch.yml"
config_format = "dsh_cordis_subagent"
""",
    )
    (home / ".example").mkdir(parents=True)
    path = home / ".example/cordis.patch.yml"
    path.write_text("# Existing shared configuration\n")
    (ws / "subagents/review.md").write_text(
        '---\ndescription: "Review"\nagents: ["example"]\n---\nReview.\n'
    )
    plan = build_subagent_plan(ws, home)
    frozen = plan.file_plans[0].final_content
    assert "aikito-subagent-review" in frozen
    path.write_text("# External edit\n")
    result = execute_subagent_plan(plan, home)
    assert not result.success and "stale" in result.error_message.lower()
    assert path.read_text() == "# External edit\n"
    plan = build_subagent_plan(ws, home)
    result = execute_subagent_plan(plan, home)
    assert result.success
    assert path.read_text() == plan.file_plans[0].final_content
    backups = list((home / ".local/state/aikito/backups").rglob("*"))
    assert any(
        item.is_file() and item.read_text() == "# External edit\n" for item in backups
    )
