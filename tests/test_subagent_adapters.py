def test_reused_codex_adapter_checks_disabled_capability(tmp_path):
    ws, home = tmp_path / "ws", tmp_path / "home"
    write_agents(
        ws,
        """[agents.example]
[agents.example.detect]
paths = [".example"]
[agents.example.subagents]
config_path = ".example/agents"
config_format = "codex_toml"
""",
    )
    (home / ".example").mkdir(parents=True)
    (home / ".example/config.toml").write_text("[agents]\nenabled = false\n")
    plan = build_subagent_plan(ws, home, allow_empty=True)
    assert not plan.can_apply
    assert any(
        op.action == "ERROR" and "disabled" in op.reason for op in plan.operations
    )


