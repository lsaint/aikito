    def test_prune_orphans_without_deleting_unrelated(self) -> None:
        sync_subagent_configs(self.aikito_dir, self.home_dir)

        claude_dir = self.home_dir / ".claude" / "agents"
        orphan_file = claude_dir / "old_agent.md"
        orphan_file.write_text(
            "---\nname: old_agent\n---\n<!-- generated by aikito from subagents/old_agent.md - edits will be overwritten -->\n",
            encoding="utf-8",
        )

        unrelated_user_file = claude_dir / "my_custom_tool.md"
        unrelated_user_file.write_text("# User tool", encoding="utf-8")

        plan, _ = build_plan(self.aikito_dir, self.home_dir)
        orphan_items = [p for p in plan if p.action == "ORPHAN"]
        self.assertEqual(len(orphan_items), 1)
        self.assertEqual(orphan_items[0].subagent_name, "old_agent")

        sync_subagent_configs(self.aikito_dir, self.home_dir, prune=False)
        self.assertTrue(orphan_file.exists())
        self.assertTrue(unrelated_user_file.exists())

        sync_subagent_configs(self.aikito_dir, self.home_dir, prune=True)
        self.assertFalse(orphan_file.exists())
        self.assertTrue(unrelated_user_file.exists())

