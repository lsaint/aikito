    def test_validate_platform_opts_dsh(self) -> None:
        valid = validate_platform_opts(
            "dsh",
            "verifier",
            {
                "tools": ["run_command"],
                "maxTokens": 4096,
                "backgroundMode": "one-shot",
                "provider": "spawn",
                "model": "deepseek-chat",
            },
        )
        self.assertEqual(valid["tools"], ["run_command"])
        self.assertEqual(valid["maxTokens"], 4096)
        self.assertEqual(valid["backgroundMode"], "one-shot")
        self.assertEqual(valid["provider"], "spawn")
        self.assertEqual(valid["model"], "deepseek-chat")

        # String tools wrapped to list
        valid_str_tool = validate_platform_opts(
            "dsh", "verifier", {"tools": "run_command"}
        )
        self.assertEqual(valid_str_tool["tools"], ["run_command"])

        # Invalid tools
        with self.assertRaises(SubagentConfigError):
            validate_platform_opts("dsh", "verifier", {"tools": 123})
        with self.assertRaises(SubagentConfigError):
            validate_platform_opts("dsh", "verifier", {"tools": [""]})

        # Invalid maxTokens
        with self.assertRaises(SubagentConfigError):
            validate_platform_opts("dsh", "verifier", {"maxTokens": -10})
        with self.assertRaises(SubagentConfigError):
            validate_platform_opts("dsh", "verifier", {"maxTokens": "4096"})
        with self.assertRaises(SubagentConfigError):
            validate_platform_opts("dsh", "verifier", {"maxTokens": True})

        # Invalid backgroundMode
        with self.assertRaises(SubagentConfigError):
            validate_platform_opts(
                "dsh", "verifier", {"backgroundMode": "invalid_mode"}
            )

        # Unknown field
        with self.assertRaises(SubagentConfigError):
            validate_platform_opts("dsh", "verifier", {"unknown_field": "val"})

