def get_subagent_adapter(config_format: str) -> SubagentAdapter:
    try:
        return SUBAGENT_ADAPTERS[config_format]
    except KeyError as exc:
        raise SubagentConfigError(
            f"Unsupported subagent config_format '{config_format}'"
        ) from exc
